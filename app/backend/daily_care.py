def _ev(keys, k=1):
    """从本地库取证据片段"""
    try:
        return LIB.search([x for x in keys if x], top_k=k)
    except Exception:
        return []


def _item(text, keys, k=1, note=""):
    return {"text": text, "note": note, "evidence": _ev(keys, k)}


