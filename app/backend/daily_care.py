        {"id": "c1", "time": "晨起", "task": "不急看手机：先远眺窗外 2 分钟，做一轮运目",
         "note": "久视伤血，晨起第一次用眼先放松调节"},
        {"id": "c2", "time": "工作时", "task": f"每 {wm} 分钟起身休息 5 分钟（远眺 + 熨目）",
         "note": "可开启本页护眼定时器自动提醒"},
        {"id": "c3", "time": "午间", "task": "午休闭目 10~15 分钟，忌趴压眼球",
         "note": "闭目养神养肝血，勿压迫眼球（青光眼尤忌）"},
        {"id": "c4", "time": "下午", "task": "户外光照活动或窗边远眺 10 分钟",
         "note": "目浴阳光，青少年近视防控关键"},
